#!/usr/bin/env python3
"""Emit vulkan_shaders.h from compiled .spv files (little-endian uint32 words)."""
import struct
import sys


def emit(name, path):
    data = open(path, "rb").read()
    if len(data) % 4:
        raise SystemExit(f"{path}: size not a multiple of 4")
    words = struct.unpack("<%dI" % (len(data) // 4), data)

    out = [f"static const uint32_t {name}[] = {{"]
    for i in range(0, len(words), 8):
        chunk = ", ".join(f"0x{w:08x}u" for w in words[i:i + 8])
        out.append(f"    {chunk},")
    out.append("};")
    out.append(f"static const unsigned {name}_len = {len(words)};")
    return "\n".join(out)


def main():
    if len(sys.argv) != 4:
        raise SystemExit("usage: spv2h.py f32 quant gemm")

    body = "\n\n".join([
        emit("matmul_f32_spv", sys.argv[1]),
        emit("matmul_quant_spv", sys.argv[2]),
        emit("matmul_gemm_spv", sys.argv[3]),
    ])

    print("""/* Generated by shaders/spv2h.py — do not edit. */
#ifndef MOE_VULKAN_SHADERS_H
#define MOE_VULKAN_SHADERS_H

#include <stdint.h>

#define MOE_VULKAN_HAVE_SHADERS 1

""" + body + """

#endif /* MOE_VULKAN_SHADERS_H */""")


if __name__ == "__main__":
    main()
